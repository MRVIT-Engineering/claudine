fn main() {
    // Tauri embeds the icons at compile time but only watches tauri.conf.json, so a
    // changed icon would otherwise keep the old one in the binary.
    println!("cargo:rerun-if-changed=icons");
    // Listing commands here makes each one deny-by-default: the webview can only
    // call a command that a capability file grants.
    let manifest = tauri_build::AppManifest::new().commands(&[
        "app_version",
        "open_project",
        "current_project",
        "list_dir",
        "read_file",
        "save_file",
        "blame_line",
        "git_log",
        "git_commit_files",
        "git_status",
        "git_diff",
        "list_files",
        "get_settings",
        "set_settings",
        "claude_status",
        "start_session",
        "send_message",
        "answer_permission",
        "interrupt_session",
        "stop_session",
        "set_mode",
        "set_model",
        "set_effort",
        "list_models",
        "list_accounts",
        "add_account",
        "update_account",
        "remove_account",
        "account_status",
        "sign_in",
        "submit_sign_in_code",
        "cancel_sign_in",
        "sign_out",
        "new_run_info",
        "start_run",
        "list_runs",
        "watch_runs",
        "run_transcript",
        "send_run_message",
        "answer_run_permission",
        "stop_run",
        "resume_run",
        "review_run_now",
        "run_changes",
        "add_run_comment",
        "delete_run_comment",
        "set_run_viewed",
        "request_run_changes",
        "gh_status",
        "approve_run",
        "discard_run",
        "open_run_in_editor",
        "set_run_options",
    ]);
    let attributes = tauri_build::Attributes::new().app_manifest(manifest);
    tauri_build::try_build(attributes).expect("tauri-build failed");
}
